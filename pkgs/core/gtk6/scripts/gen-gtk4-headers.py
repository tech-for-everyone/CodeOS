# gen-gtk4-headers.py -- generate the headers and bodies that upstream GTK4's
# meson build would generate, so gtk6's freestanding Makefile can compile the
# imported gtk/, gdk/ and gsk/ sources.
#
# This is *not* a build of GTK.  It is the generated-header half of one,
# reproduced with the target-built glib tools that scripts/build-glib.sh leaves
# in build/glib/:
#
#   glib-mkenums             enum type tables      (gdk, gsk, gtk, gtk/css, gtk/svg)
#   glib-genmarshal          marshallers           (gdk, gtk)
#   gdbus-codegen            D-Bus proxies         (gtk/gtkdbusinterfaces)
#   gen-visibility-macros.py version/visibility macros (gdk/version)
#
# Everything lands under build/gen/, mirroring the source layout.  The
# Makefile adds that tree to the include path and compiles the generated .c.
#
# The file lists are read from the imported meson.build files, so they stay in
# sync with upstream's own lists rather than being copied by hand here.
#
# What this does *not* do yet: gnome.compile_resources() output
# (gdkresources.c, gskresources.c, gtkresources.c).  Those need the theme CSS
# that upstream builds with sassc; they are link-time subscribers, not a
# compile-time dependency, so they are deferred.
#
# Usage:
#   scripts/gen-gtk4-headers.py [--out DIR] [--glib-build DIR]

import argparse
import re
import subprocess
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

# GTK version the import was taken from (gtk4/meson.build `version:`).  The
# version macros are generated up to minor+1 (range() in
# build-aux/meson/gen-visibility-macros.py), which is how GDK_AVAILABLE_IN_4_26
# exists while the tree is 4.25.
GTK_VERSION = "4.25.0"

# Our configuration, in the shape of GTK's meson cdata.  Anything not listed is
# left undefined, which selects GTK's portable fallback -- what a freestanding
# target wants.  The windowing/rendering defines mirror a desktop build with
# only the Qt backend: cairo stays "on" (gdkcairo.c is unconditional upstream),
# GL and Vulkan are off because those renderers were pruned.
CONFIG_H = """\
/* config.h -- generated by gtk6 scripts/gen-gtk4-headers.py */
#pragma once

#define PACKAGE_VERSION "{version}"
#define GETTEXT_PACKAGE "gtk40"
#define GTK_LOCALEDIR "/usr/share/locale"
#define GTK_DATADIR "/usr/share"
#define GTK_LIBDIR "/usr/lib"
#define GTK_SYSCONFDIR "/etc"
#define SYMBOL_VISIBILITY "hidden"

#define GLIB_DISABLE_DEPRECATION_WARNINGS 1
#define HAVE_UINT128_T 1

#define HAVE_UNISTD_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_DIRENT_H 1
#define HAVE_MEMMOVE 1
#define HAVE_BIND_TEXTDOMAIN_CODESET 1
""".format(version=GTK_VERSION)

# gdk/gdkconfig.h.meson -> gdkconfig.h.  Value is 1 (define) or 0 (undef).
GDKCONFIG = {
    "GDK_WINDOWING_X11": 0,
    "GDK_WINDOWING_ANDROID": 0,
    "GDK_WINDOWING_BROADWAY": 0,
    "GDK_WINDOWING_MACOS": 0,
    "GDK_WINDOWING_WAYLAND": 0,
    "GDK_WINDOWING_WIN32": 0,
    "GDK_RENDERING_CAIRO": 1,
    "GDK_RENDERING_GL": 0,
    "GDK_RENDERING_VULKAN": 0,
}

GTKCONFIG = {
    "GTK_ACCESSIBILITY_ATSPI": 0,
}


def run(cmd, cwd=None):
    print("  " + " ".join(str(c) for c in cmd))
    subprocess.run([str(c) for c in cmd], cwd=cwd, check=True)


# ---------------------------------------------------------------------------
# Reading upstream's own file lists out of meson.build
# ---------------------------------------------------------------------------

_ASSIGN = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(\+?=)\s*(.*)$")


def parse_lists(meson_path):
    """Return {var: [names]} for every list-ish assignment in a meson.build.

    Handles `v = files([...])`, `v += [...]`, `v = A + B` and multi-line
    bracketed lists -- every shape GTK's meson uses for source lists.
    """
    lines = Path(meson_path).read_text(encoding="utf-8").splitlines()
    lists = {}
    i = 0
    while i < len(lines):
        m = _ASSIGN.match(lines[i])
        if not m:
            i += 1
            continue
        name, op, rhs = m.group(1), m.group(2), m.group(3)
        stmt = rhs
        depth = (rhs.count("(") + rhs.count("[")
                 - rhs.count(")") - rhs.count("]"))
        while depth > 0 and i + 1 < len(lines):
            i += 1
            stmt += "\n" + lines[i]
            depth += (lines[i].count("(") + lines[i].count("[")
                      - lines[i].count(")") - lines[i].count("]"))

        if "files(" in stmt or "[" in stmt:
            entries = re.findall(r"['\"]([^'\"]+)['\"]", stmt)
        else:
            # A plain concatenation of earlier lists: v = a + b
            entries = []
            for ident in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", stmt):
                entries.extend(lists.get(ident, []))

        if op == "=":
            lists[name] = list(entries)
        else:
            lists.setdefault(name, []).extend(entries)
        i += 1
    return lists


def existing(base, names):
    """Resolve names under base, dropping the ones a pruned dir removed."""
    return [Path(base) / n for n in names if (Path(base) / n).is_file()]


# ---------------------------------------------------------------------------
# glib-mkenums: meson wraps it two ways
# ---------------------------------------------------------------------------

def mkenums_simple(tool, name, sources, out_dir, decorator="",
                   header_prefix="", body_prefix=""):
    """gnome.mkenums_simple, reproduced from mesonbuild/modules/gnome.py."""
    hdr = f"{name}.h"

    fhead = ""
    if body_prefix:
        fhead += "%s\n" % body_prefix
    fhead += '#include "%s"\n' % hdr
    for src in sources:
        fhead += '#include "%s"\n' % Path(src).name
    fhead += textwrap.dedent(
        """
        #define C_ENUM(v) ((gint) v)
        #define C_FLAGS(v) ((guint) v)
        """)

    c_cmd = [
        tool,
        "--fhead", fhead,
        "--fprod", textwrap.dedent(
            """
            /* enumerations from "@basename@" */
            """),
        "--vhead", textwrap.dedent(
            f"""
            GType
            @enum_name@_get_type (void)
            {{
                static gsize gtype_id = 0;
                static const G@Type@Value values[] = {{"""),
        "--vprod", '        { C_@TYPE@ (@VALUENAME@), "@VALUENAME@", "@valuenick@" },',
        "--vtail", textwrap.dedent(
            """\
                    { 0, NULL, NULL }
                };
                if (g_once_init_enter (&gtype_id)) {
                    GType new_type = g_@type@_register_static (g_intern_static_string ("@EnumName@"), values);
                    g_once_init_leave (&gtype_id, new_type);
                }
                return (GType) gtype_id;
            }"""),
        "--output", out_dir / f"{name}.c",
    ] + sources

    if header_prefix and not header_prefix.endswith("\n"):
        header_prefix += "\n"
    extra_newline = "\n" if decorator else ""
    h_cmd = [
        tool,
        "--fhead", textwrap.dedent(
            f"""\
            #pragma once

            #include <glib-object.h>
            {header_prefix}
            G_BEGIN_DECLS
            """),
        "--fprod", textwrap.dedent(
            """
            /* enumerations from "@basename@" */
            """),
        "--vhead", extra_newline + textwrap.dedent(
            f"""\
            {decorator}
            GType @enum_name@_get_type (void);
            #define @ENUMPREFIX@_TYPE_@ENUMSHORT@ (@enum_name@_get_type())"""),
        "--ftail", textwrap.dedent(
            """
            G_END_DECLS"""),
        "--output", out_dir / f"{name}.h",
    ] + sources

    run(c_cmd)
    run(h_cmd)


def mkenums_template(tool, name, sources, c_template, h_template, out_dir):
    """gnome.mkenums with explicit templates (gsk, gtk, css, svg)."""
    run([tool, "--template", c_template,
         "--output", out_dir / f"{name}.c"] + sources)
    run([tool, "--template", h_template,
         "--output", out_dir / f"{name}.h"] + sources)


def genmarshal(tool, name, list_file, prefix, out_dir, include_header=None,
               cwd=None):
    """gnome.genmarshal: header then body, --quiet --prefix ... --valist-marshallers.

    Runs in cwd and is given the .list by relative name, so the file it records
    in the generated comments is stable across checkouts.
    """
    base = [tool, "--quiet", "--prefix", prefix, "--valist-marshallers"]
    run(base + ["--output", out_dir / f"{name}.h",
                "--header", list_file, "--pragma-once"], cwd=cwd)
    body = base + ["--output", out_dir / f"{name}.c", "--body", list_file]
    if include_header is not None:
        body += ["--include-header", include_header]
    run(body, cwd=cwd)


# ---------------------------------------------------------------------------
# configure_file() equivalents
# ---------------------------------------------------------------------------

def mesondefine(text, mapping):
    """Substitute `#mesondefine NAME` with `#define NAME 1` or `#undef NAME`."""
    out = []
    for line in text.splitlines():
        m = re.match(r"#mesondefine\s+(\w+)\s*$", line)
        if m:
            name = m.group(1)
            val = mapping.get(name, 0)
            out.append(f"#define {name} 1" if val else f"#undef {name}")
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(HERE / "build/gen"),
                    help="output directory (default: build/gen)")
    ap.add_argument("--glib-build", default=str(HERE / "build/glib"),
                    help="glib build tree holding the host-side tools")
    args = ap.parse_args()

    src = HERE
    out = Path(args.out).resolve()
    gb = Path(args.glib_build).resolve()

    mkenums = gb / "gobject/glib-mkenums"
    genmarshal_tool = gb / "gobject/glib-genmarshal"
    gdbus = gb / "gio/gdbus-2.0/codegen/gdbus-codegen"
    visgen = src / "build-aux/meson/gen-visibility-macros.py"

    for tool in (mkenums, genmarshal_tool, gdbus, visgen):
        if not tool.exists():
            sys.exit(f"gen-gtk4-headers: missing tool {tool}\n"
                     f"  (scripts/build-glib.sh must be run first)")

    for d in (out / "gdk/version", out / "gsk", out / "gtk/css", out / "gtk/svg"):
        d.mkdir(parents=True, exist_ok=True)

    print("==> config headers")
    (out / "config.h").write_text(CONFIG_H)
    (out / "gdk/gdkconfig.h").write_text(
        mesondefine((src / "gdk/gdkconfig.h.meson").read_text(), GDKCONFIG))
    (out / "gtk/gtkconfig.h").write_text(
        mesondefine((src / "gtk/gtkconfig.h.meson").read_text(), GTKCONFIG))

    print("==> version + visibility macros (build-aux/meson/gen-visibility-macros.py)")
    # gdk version macros need @GDK_VERSIONS@ substituted in the .in file.
    run([sys.executable, visgen, GTK_VERSION, "versions-macros",
         src / "gdk/version/gdkversionmacros.h.in",
         out / "gdk/version/gdkversionmacros.h"])
    run([sys.executable, visgen, GTK_VERSION, "visibility-macros", "GDK",
         out / "gdk/version/gdk-visibility.h"])

    print("==> gdk")
    gdk = parse_lists(src / "gdk/meson.build")
    gdk_headers = existing(src / "gdk", gdk["gdk_public_headers"])
    mkenums_simple(mkenums, "gdkenumtypes", gdk_headers, out / "gdk",
                   decorator="GDK_AVAILABLE_IN_ALL",
                   header_prefix='#include "version/gdkversionmacros.h"',
                   body_prefix='#include "config.h"')
    genmarshal(genmarshal_tool, "gdkmarshalers",
               "gdk/gdkmarshalers.list", "_gdk_marshal", out / "gdk",
               include_header="gdkmarshalers.h", cwd=src)

    print("==> gsk")
    gsk = parse_lists(src / "gsk/meson.build")
    gsk_headers = existing(src / "gsk", gsk["gsk_public_headers"])
    mkenums_template(mkenums, "gskenumtypes", gsk_headers,
                     src / "gsk/gskenumtypes.c.template",
                     src / "gsk/gskenumtypes.h.template", out / "gsk")

    print("==> gtk")
    gtk = parse_lists(src / "gtk/meson.build")
    gtk_public = existing(src / "gtk", gtk["gtk_public_headers"])
    gtk_private = existing(src / "gtk", gtk["gtk_private_type_headers"])
    # gtk_deprecated_headers / gtk_print_headers live in pruned subdirs; the
    # lists are absent here and the imports are gone, so they contribute none.
    mkenums_template(mkenums, "gtktypebuiltins", gtk_public,
                     src / "gtk/gtktypebuiltins.c.template",
                     src / "gtk/gtktypebuiltins.h.template", out / "gtk")
    mkenums_template(mkenums, "gtkprivatetypebuiltins", gtk_private,
                     src / "gtk/gtkprivatetypebuiltins.c.template",
                     src / "gtk/gtkprivatetypebuiltins.h.template", out / "gtk")
    genmarshal(genmarshal_tool, "gtkmarshalers",
               "gtk/gtkmarshalers.list", "_gtk_marshal", out / "gtk",
               include_header="gtkmarshalers.h", cwd=src)

    print("==> gtk/css")
    css = parse_lists(src / "gtk/css/meson.build")
    css_public = existing(src / "gtk/css", css["gtk_css_public_headers"])
    mkenums_template(mkenums, "gtkcssenumtypes", css_public,
                     src / "gtk/css/gtkcssenumtypes.c.template",
                     src / "gtk/css/gtkcssenumtypes.h.template", out / "gtk/css")

    print("==> gtk/svg")
    svg = parse_lists(src / "gtk/svg/meson.build")
    svg_public = existing(src / "gtk/svg", svg["gtk_svg_public_headers"])
    mkenums_template(mkenums, "gtksvgenumtypes", svg_public,
                     src / "gtk/svg/gtksvgenumtypes.c.template",
                     src / "gtk/svg/gtksvgenumtypes.h.template", out / "gtk/svg")

    print("==> gtktypefuncs.inc")
    typefuncs_in = (gdk_headers + gsk_headers + gtk_public + gtk_private
                    + svg_public
                    + [str(out / "gtk/gtktypebuiltins.h"),
                       str(out / "gtk/css/gtkcssenumtypes.h"),
                       str(out / "gdk/gdkenumtypes.h"),
                       str(out / "gsk/gskenumtypes.h")])
    run([sys.executable, src / "gtk/gentypefuncs.py",
         out / "gtk/gtktypefuncs.inc"] + typefuncs_in)

    print(f"\n==> generated into {out}")


if __name__ == "__main__":
    main()
