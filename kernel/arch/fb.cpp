void fb_write_at(int row, int col, const char *s) {
    int old_x = cur_x, old_y = cur_y;
    cur_x = col; cur_y = row;
    while (*s) fb_putchar(*s++);
    cur_x = old_x; cur_y = old_y;
}
void fb_fill_row(int row) {
    if (!fb_initialized) return;
    pm_composite_rect(fb_get_active_buffer(), fb_pixstride(), fb_clip(),
                      0, row * char_h, (int)fb.width, char_h, bg_color);
}

