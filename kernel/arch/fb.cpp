fb_info_t fb;
static int fb_initialized = 0;
static uint32_t fg_color = 0xFFFFFFFF;
static uint32_t bg_color = 0xFF000000;
static int cur_x = 0, cur_y = 0;
static int char_w = 8, char_h = 16;

/* Xserver screen (replaces raw backbuffer) */
static xs_screen_t *xs_screen = 0;
static int back_buffer_active = 0;
static int backbuffer_ok = 0;

/* True double buffer: allocate a full-screen back buffer in kernel heap */
static uint32_t *db_back = 0;      /* back buffer pixel data */
static uint32_t *db_front = 0;     /* front buffer = physical FB */
static uint32_t  db_buf_bytes = 0; /* size of one buffer in bytes */
static uint32_t  db_buf_pages = 0; /* pages allocated for one buffer */

static inline uint32_t *fb_base(void) {
    return (uint32_t*)phys_to_virt(fb.addr);
}

static inline uint32_t *pixel_at(int x, int y) {
    return fb_base() + y * (fb.pitch / 4) + x;
}

static inline uint32_t *fb_pixbuf(void) {
    return fb_base();
}
static inline int fb_pixstride(void) { return (int)fb.pitch; }
static inline pm_rect_t fb_clip(void) {
    pm_rect_t r = {0, 0, (int)fb.width, (int)fb.height};
    return r;
}

int fb_backbuffer_init(void) {
    if (!fb_initialized || fb.addr == 0) {
        backbuffer_ok = 0;
        return 0;
    }

    /* Allocate a full-screen back buffer from PMM */
    db_buf_bytes = fb.pitch * fb.height;
    db_buf_pages = (db_buf_bytes + 0xFFF) / 0x1000;
    if (db_buf_pages < 1) db_buf_pages = 1;

    uint64_t back_phys = pmm_alloc_pages(db_buf_pages);
    if (!back_phys) {
        backbuffer_ok = 0;
        return 0;
    }
    db_back = (uint32_t*)phys_to_virt(back_phys);
    db_front = (uint32_t*)phys_to_virt(fb.addr);
    /* Clear the back buffer */
    uint32_t *tmp = db_back;
    uint32_t words = db_buf_bytes / 4;
    for (uint32_t i = 0; i < words; i++) tmp[i] = 0;

    xs_screen = xs_screen_create(fb.width, fb.height,
                                  (uint32_t*)fb.addr, fb.pitch);
    if (!xs_screen) {
        pmm_free_pages(back_phys, db_buf_pages);
        db_back = 0;
        backbuffer_ok = 0;
        return 0;
    }
    backbuffer_ok = 1;
    return 1;
}

void fb_backbuffer_begin(void) {
    back_buffer_active = backbuffer_ok;
}

void fb_backbuffer_end(void) {
    if (!back_buffer_active) return;
    back_buffer_active = 0;

    /* Blit back buffer to physical framebuffer (fast memcpy, no tearing) */
    if (db_back && db_front) {
        uint32_t *src = db_back;
        uint32_t *dst = db_front;
        uint32_t words = db_buf_bytes / 4;
        for (uint32_t i = 0; i < words; i++) dst[i] = src[i];
        /* Clear back buffer for next frame */
        for (uint32_t i = 0; i < words; i++) src[i] = 0;
    }

    fb_cursor_invalidate();
}

uint64_t fb_get_addr_phys(void) {
    return fb.addr;
}

uint8_t fb_get_bpp(void) {
    return fb.bpp;
}

int fb_available(void) {
    return fb_initialized && fb.width != 0 && fb.height != 0;
}

int fb_init(uint64_t addr, uint32_t width, uint32_t height,
            uint32_t pitch, uint32_t bpp, uint32_t type) {
    fb.addr = addr;
    fb.width = width;
    fb.height = height;
    fb.pitch = pitch;
    fb.bpp = (uint8_t)bpp;
    fb.type = (uint8_t)type;
    fb_initialized = 1;
    cur_x = 0;
    cur_y = 0;
    fg_color = 0xFFFFFFFF;
    bg_color = 0xFF000000;
    fb_fill(bg_color);
    return 1;
}

void fb_putpixel(uint32_t x, uint32_t y, uint32_t color) {
    if (!fb_initialized) return;
    if (x >= fb.width || y >= fb.height) return;

    uint32_t *active = fb_get_active_buffer();
    if (fb.bpp == 32) {
        uint32_t *p = active + y * (fb.pitch / 4) + x;
        *p = color;
    } else if (fb.bpp == 24) {
        uint8_t *p = (uint8_t*)active + y * fb.pitch + x * 3;
        p[0] = color & 0xFF;
        p[1] = (color >> 8) & 0xFF;
        p[2] = (color >> 16) & 0xFF;
    }
}

void fb_fill(uint32_t color) {
    if (!fb_initialized) return;
    pm_composite_rect(fb_get_active_buffer(), fb_pixstride(), fb_clip(),
                      0, 0, (int)fb.width, (int)fb.height, color);
}

