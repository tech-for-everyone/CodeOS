uint32_t fb_getwidth(void) { return fb.width; }
uint32_t fb_getheight(void) { return fb.height; }
int fb_get_rows(void) { return (int)(fb.height / char_h); }
int fb_get_cols(void) { return (int)(fb.width / char_w); }
