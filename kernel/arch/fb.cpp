static void fb_drawglyph_px(uint32_t *buf, int stride, pm_rect_t clip,
                            int x, int y, const uint8_t *glyph, int gw, int gh,
                            uint32_t fg, uint32_t bg) {
    pm_rect_t r = pixelman_rect_intersect(clip, (pm_rect_t){x, y, x + gw, y + gh});
    if (pixelman_rect_empty(r)) return;
    int stride_words = stride / 4;
    for (int row = r.y1; row < r.y2; row++) {
        int gy = row - y;
        if (gy < 0 || gy >= gh) continue;
        uint32_t *line = buf + row * stride_words;
        for (int col = r.x1; col < r.x2; col++) {
            int gx = col - x;
            if (gx < 0 || gx >= gw) continue;
            int bit = (glyph[gy] >> (7 - gx)) & 1;
            if (bit) line[col] = fg;
            else if (bg != 0) line[col] = bg;
        }
    }
}

void fb_drawstr_px(uint32_t x, uint32_t y, const char *s, uint32_t fg, uint32_t bg) {
    if (!fb_initialized || !s) return;
    uint32_t *buf = fb_get_active_buffer();
    int stride = fb_pixstride();
    pm_rect_t clip = fb_clip();
    while (*s) {
        fb_drawglyph_px(buf, stride, clip, (int)x, (int)y,
                        font8x16[(unsigned char)*s], 8, 16, fg, bg);
        x += 8;
        s++;
    }
}

int fb_text_width(const char *s) {
    if (!s) return 0;
    return (int)strlen(s) * char_w;
}

void fb_write_styled(int row, int col, const char *s, uint32_t fg, uint32_t bg) {
    if (!fb_initialized || !s) return;
    uint32_t *buf = fb_get_active_buffer();
    int stride = fb_pixstride();
    pm_rect_t clip = fb_clip();
    int x = col * char_w;
    int y = row * char_h;
    while (*s) {
        pm_composite_glyph(buf, stride, clip, x, y,
                           font8x16[(unsigned char)*s], 8, 16, fg, bg);
        x += char_w;
        s++;
    }
}

void fb_fill_row_bg(int row, uint32_t bg) {
    if (!fb_initialized) return;
    pm_composite_rect(fb_get_active_buffer(), fb_pixstride(), fb_clip(),
                      0, row * char_h, (int)fb.width, char_h, bg);
}

void fb_fillrect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    if (!fb_initialized) return;
    pm_composite_rect(fb_get_active_buffer(), fb_pixstride(), fb_clip(),
                      (int)x, (int)y, (int)w, (int)h, color);
}

void fb_drawrect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    if (!fb_initialized) return;
    uint32_t *buf = fb_get_active_buffer();
    int stride = fb_pixstride();
    pm_rect_t clip = fb_clip();
    pm_composite_line(buf, stride, clip, (int)x, (int)y, (int)(x + w - 1), (int)y, color);
    pm_composite_line(buf, stride, clip, (int)x, (int)(y + h - 1), (int)(x + w - 1), (int)(y + h - 1), color);
    pm_composite_line(buf, stride, clip, (int)x, (int)y, (int)x, (int)(y + h - 1), color);
    pm_composite_line(buf, stride, clip, (int)(x + w - 1), (int)y, (int)(x + w - 1), (int)(y + h - 1), color);
}
