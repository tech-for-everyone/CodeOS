/* Default font face */
static codeos_font_face_t default_face = {0};

void codeos_font_init(void) {
    default_face.bitmap = (const uint8_t *)codeos_font8x16;
    default_face.glyph_width = 8;
    default_face.glyph_height = 16;
    default_face.num_glyphs = 256;
    default_face.metrics.width = 8;
    default_face.metrics.height = 16;
    default_face.metrics.ascent = 12;
    default_face.metrics.descent = 4;
    default_face.metrics.leading = 2;
}

codeos_font_face_t *codeos_font_default(void) {
    if (!default_face.bitmap) codeos_font_init();
    return &default_face;
}

codeos_font_face_t *codeos_font_create_bitmap(
    const uint8_t *bitmap,
    int glyph_width,
    int glyph_height,
    int num_glyphs
) {
    if (!bitmap || glyph_width <= 0 || glyph_height <= 0) return 0;

    static codeos_font_face_t face;
    face.bitmap = bitmap;
    face.glyph_width = glyph_width;
    face.glyph_height = glyph_height;
    face.num_glyphs = num_glyphs > 0 ? num_glyphs : 256;
    face.metrics.width = glyph_width;
    face.metrics.height = glyph_height;
    face.metrics.ascent = (glyph_height * 3) / 4;
    face.metrics.descent = glyph_height / 4;
    face.metrics.leading = 2;
    return &face;
}

void codeos_font_destroy(codeos_font_face_t *face) {
    (void)face;
    /* Static faces can't be freed */
}

const uint8_t *codeos_font_get_glyph(
    codeos_font_face_t *face,
    int codepoint
) {
    if (!face || !face->bitmap) return 0;
    if (codepoint < 0 || codepoint >= face->num_glyphs) return 0;
    return face->bitmap + codepoint * face->glyph_height;
}

int codeos_font_get_glyph_metrics(
    codeos_font_face_t *face,
    int codepoint,
    codeos_glyph_metrics_t *metrics
) {
    if (!face || !metrics) return -1;
    if (codepoint < 0 || codepoint >= face->num_glyphs) return -1;

    metrics->width = face->glyph_width;
    metrics->height = face->glyph_height;
    metrics->bearing_x = 0;
    metrics->bearing_y = face->metrics.ascent;
    metrics->advance = face->glyph_width;
    return 0;
}

void codeos_font_get_metrics(
    codeos_font_face_t *face,
    codeos_font_metrics_t *metrics
) {
    if (!face || !metrics) return;
    *metrics = face->metrics;
}

int codeos_font_measure_text(
    codeos_font_face_t *face,
    const char *text,
    int length
) {
    if (!face || !text) return 0;
    if (length < 0) {
        length = 0;
        while (text[length]) length++;
    }
    return length * face->glyph_width;
}
